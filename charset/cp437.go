// ToCP437 converts a Unicode character to CP437, returning '?' when the
// character has no CP437 representation.
func ToCP437(ch rune) byte {
	if ch < 0x20 {
		return '?'
	}
	if ch < 0x80 {
		return byte(ch)
	}
	for i, v := range cp437Lookup1 {
		if v == ch {
			return byte(0x01 + i)
		}
	}
	for i, v := range cp437Lookup2 {
		if v == ch {
			return byte(0x7f + i)
		}
	}
	return '?'
}

// FromCP437 converts a CP437 byte to Unicode. Control characters below
// 0x20 map to their symbol glyphs; zero maps to zero.
func FromCP437(ch byte) rune {
	if ch > 0x7f {
		return cp437Lookup2[ch-0x7f]
	}
	if ch >= 0x20 {
		return rune(ch)
	}
	if ch > 0 {
		return cp437Lookup1[ch-0x01]
	}
	return 0
}

// ToASCII converts a Unicode character to a graphically similar ASCII
// character, or '?' when none exists.
func ToASCII(ch rune) byte {
	if ch < 0x80 {
		return byte(ch)
	}
	if ch > 0xff00 && ch < 0xff5f {
		return byte(' ' + (ch - 0xff00))
	}
	switch ch {
	case 0x00a0, 0x3000:
		return ' '
	case 0x00a3:
		return 'f'
	case 0x00b0:
		return '\''
	case 0x00b1:
		return '#'
	case 0x00b7, 0x2219, 0x30fb:
		return '.'
	case 0x03c0:
		return '*'
	case 0x2018, 0x2019:
		return '\''
	case 0x201c, 0x201d:
		return '"'
	case 0x2190:
		return '<'
	case 0x2191:
		return '^'
	case 0x2192:
		return '>'
	case 0x2193:
		return 'v'
	case 0x2260:
		return '!'
	case 0x2261:
		return '='
	case 0x2264:
		return '<'
	case 0x2265:
		return '>'
	case 0x23ba, 0x23bb, 0x23bc, 0x23bd, 0x2500, 0x2550:
		return '-'
	case 0x2502, 0x2551:
		return '|'
	case 0x250c, 0x2552, 0x2553, 0x2554, 0x2514, 0x2558, 0x2559, 0x255a,
		0x251c, 0x255e, 0x255f, 0x2560, 0x252c, 0x2564, 0x2565, 0x2566,
		0x2534, 0x2567, 0x2568, 0x2569, 0x253c, 0x256a, 0x256b, 0x256c,
		0x2510, 0x2555, 0x2556, 0x2557, 0x2518, 0x255b, 0x255c, 0x255d,
		0x2524, 0x2561, 0x2562, 0x2563:
		return '+'
	case 0x2591, 0x2592, 0x2593, 0x2588, 0x258c, 0x2590, 0x25a0, 0x25ac, 0x25ae:
		return '#'
	case 0x2580:
		return '"'
	case 0x2584:
		return ','
	case 0x25c6, 0x2666:
		return '+'
	case 0x2022, 0x25cb, 0x25cf, 0x2603, 0x263c:
		return 'o'
	case 0x301c:
		return '~'
	}
	return '?'
}
