func exportHTML(v view) []byte {
	var b bytes.Buffer
	b.WriteString("<!DOCTYPE html PUBLIC \"-//W3C//DTD XHTML 1.0 Strict//EN\"\n")
	b.WriteString("   \"http://www.w3.org/TR/xhtml1/DTD/xhtml1-strict.dtd\">\n")
	b.WriteString("<html xmlns=\"http://www.w3.org/1999/xhtml\" lang=\"en\" xml:lang=\"en\">")
	b.WriteString("<head>\n")
	fmt.Fprintf(&b, "<title>Generated by libcaca %s</title>\n", Version)
	b.WriteString("</head><body>\n")
	b.WriteString("<div style=\"font-family: monospace, fixed; font-weight: bold;\">\n")

	for y := 0; y < v.h; y++ {
		for x := 0; x < v.w; {
			cell := v.cells[y*v.w+x]
			b.WriteString("<span style=\"")
			if cell.A.FG() != canvas.Default {
				fmt.Fprintf(&b, ";color:#%.03x", cell.A.RGB12FG())
			}
			if cell.A.BG() < 0x10 {
				fmt.Fprintf(&b, ";background-color:#%.03x", cell.A.RGB12BG())
			}
			if cell.A.Styles()&canvas.Bold != 0 {
				b.WriteString(";font-weight:bold")
			}
			if cell.A.Styles()&canvas.Italics != 0 {
				b.WriteString(";font-style:italic")
			}
			if cell.A.Styles()&canvas.Underline != 0 {
				b.WriteString(";text-decoration:underline")
			}
			if cell.A.Styles()&canvas.Blink != 0 {
				b.WriteString(";text-decoration:blink")
			}
			b.WriteString("\">")

			n := 0
			for x+n < v.w && v.cells[y*v.w+x+n].A == cell.A {
				n++
			}
			for i := 0; i < n; i++ {
				ch := v.cells[y*v.w+x+i].Ch
				switch {
				case ch == canvas.MagicFullwidth:
					// skip
				case ch <= 0x20, ch >= 0x7f && ch <= 0xa0:
					b.WriteString("&#160;")
				case ch == '&':
					b.WriteString("&amp;")
				case ch == '<':
					b.WriteString("&lt;")
				case ch == '>':
					b.WriteString("&gt;")
				case ch == '"':
					b.WriteString("&quot;")
				case ch == '\'':
					b.WriteString("&#39;")
				case ch < 0x80:
					b.WriteByte(byte(ch))
				case ch <= 0x10fffd && (ch&0xfffe) != 0xfffe && (ch < 0xd800 || ch > 0xdfff):
					fmt.Fprintf(&b, "&#%d;", ch)
				default:
					b.WriteString("&#65533;")
				}
			}
			b.WriteString("</span>")
			x += n
		}
		b.WriteString("<br />\n")
	}

	b.WriteString("</div></body></html>\n")
	return b.Bytes()
}

// exportHTML3 produces a table-based document for very old browsers. The
// grouping, colspan compression and tag placement follow libcaca's C exporter
// so the output is byte-compatible.
func exportHTML3(v view) []byte {
	bitmap := make([]byte, (v.w+7)/8)
	hasMulti := false

	bit := func(x int) bool {
		return bitmap[x/8]&(1<<uint(x%8)) != 0
	}
	setBit := func(x int) {
		bitmap[x/8] |= 1 << uint(x%8)
	}
	cell := func(x, y int) canvas.Cell { return v.cells[y*v.w+x] }

	for y := 0; y < v.h; y++ {
		for x := 1; x < v.w; x++ {
			prev, cur := cell(x-1, y), cell(x, y)
			if !bit(x) &&
				((prev.Ch == canvas.MagicFullwidth && !charset.IsFullwidth(cur.Ch)) ||
					prev.A.BG() != cur.A.BG() ||
					(cur.A.BG() < 0x10 && prev.A.RGB24BG() != cur.A.RGB24BG())) {
				hasMulti = true
				setBit(x)
			}
		}
	}

	var b bytes.Buffer
	b.WriteString("<table border=\"0\" cellpadding=\"0\" cellspacing=\"0\" summary=\"[libcaca canvas export]\">\n")

	for y := 0; y < v.h; y++ {
		b.WriteString("<tr>")
		for x := 0; x < v.w; {
			length := 1
			for x+length < v.w {
				cur := cell(x+length, y)
				included := (y != 0 &&
					cur.Ch > 0x20 &&
					(cur.Ch < 0x7f || cur.Ch > 0xa0)) ||
					!bit(x+length) ||
					cur.Ch == canvas.MagicFullwidth ||
					v.h == 1
				if !included {
					break
				}
				prev := cell(x+length-1, y)
				if prev.Ch == canvas.MagicFullwidth && !charset.IsFullwidth(cur.Ch) {
					break
				}
				if cur.A.BG() != cell(x, y).A.BG() {
					break
				}
				if cell(x, y).A.BG() < 0x10 && cur.A.RGB24BG() != cell(x, y).A.RGB24BG() {
					break
				}
				length++
			}

			nonblank := false
			for i := 0; i < length; i++ {
				ch := cell(x+i, y).Ch
				if !(ch <= 0x20 || (ch >= 0x7f && ch <= 0xa0)) {
					nonblank = true
					break
				}
			}

			base := cell(x, y)
			b.WriteString("<td")
			if base.A.BG() < 0x10 {
				fmt.Fprintf(&b, " bgcolor=\"#%06x\"", base.A.RGB24BG())
			}
			if hasMulti && length > 1 {
				colspan := length
				for i := 0; i < length; i++ {
					if i != 0 && !bit(x+i) {
						colspan--
					}
				}
				if colspan > 1 {
					fmt.Fprintf(&b, " colspan=\"%d\"", colspan)
				}
			}
			b.WriteString("><tt>")

			needFont := false
			for i := 0; i < length; i++ {
				c := cell(x+i, y)
				if nonblank && (i == 0 || c.A != cell(x+i-1, y).A) {
					needFont = c.A.FG() != canvas.Default
					if needFont {
						fmt.Fprintf(&b, "<font color=\"#%06x\">", c.A.RGB24FG())
					}
					if c.A.Styles()&canvas.Bold != 0 {
						b.WriteString("<b>")
					}
					if c.A.Styles()&canvas.Italics != 0 {
						b.WriteString("<i>")
					}
					if c.A.Styles()&canvas.Underline != 0 {
						b.WriteString("<u>")
					}
					if c.A.Styles()&canvas.Blink != 0 {
						b.WriteString("<blink>")
					}
				}

				switch {
				case c.Ch == canvas.MagicFullwidth:
					// skip
				case c.Ch <= 0x20, c.Ch >= 0x7f && c.Ch <= 0xa0:
					b.WriteString("&#160;")
				case c.Ch == '&':
					b.WriteString("&amp;")
				case c.Ch == '<':
					b.WriteString("&lt;")
				case c.Ch == '>':
					b.WriteString("&gt;")
				case c.Ch == '"':
					b.WriteString("&quot;")
				case c.Ch == '\'':
					b.WriteString("&#39;")
				case c.Ch < 0x80:
					b.WriteByte(byte(c.Ch))
				case c.Ch <= 0x10fffd && (c.Ch&0xfffe) != 0xfffe && (c.Ch < 0xd800 || c.Ch > 0xdfff):
					fmt.Fprintf(&b, "&#%d;", c.Ch)
				default:
					b.WriteString("&#65533;")
				}

				if nonblank && (i+1 == length || cell(x+i+1, y).A != c.A) {
					if c.A.Styles()&canvas.Blink != 0 {
						b.WriteString("</blink>")
					}
					if c.A.Styles()&canvas.Underline != 0 {
						b.WriteString("</u>")
					}
					if c.A.Styles()&canvas.Italics != 0 {
						b.WriteString("</i>")
					}
					if c.A.Styles()&canvas.Bold != 0 {
						b.WriteString("</b>")
					}
					if needFont {
						b.WriteString("</font>")
					}
				}
			}

			b.WriteString("</tt></td>")
			x += length
		}
		b.WriteString("</tr>\n")
	}
	b.WriteString("</table>\n")
	return b.Bytes()
}

func exportSVG(v view) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n")
	fmt.Fprintf(&b, "<svg width=\"%d\" height=\"%d\" viewBox=\"0 0 %d %d\" xmlns=\"http://www.w3.org/2000/svg\" xmlns:xlink=\"http://www.w3.org/1999/xlink\" xml:space=\"preserve\" version=\"1.1\"  baseProfile=\"full\">\n",
		v.w*6, v.h*10, v.w*6, v.h*10)
	b.WriteString(" <g id=\"mainlayer\" font-size=\"10\" style=\"font-family: monospace\">\n")

	for y := 0; y < v.h; y++ {
		for x := 0; x < v.w; x++ {
			cell := v.cells[y*v.w+x]
			fmt.Fprintf(&b, "<rect style=\"fill:#%.03x\" x=\"%d\" y=\"%d\" width=\"6\" height=\"10\"/>\n",
				cell.A.RGB12BG(), x*6, y*10)
		}
	}

	for y := 0; y < v.h; y++ {
		for x := 0; x < v.w; x++ {
			cell := v.cells[y*v.w+x]
			if cell.Ch == ' ' || cell.Ch == canvas.MagicFullwidth {
				continue
			}
			fontWeight, fontStyle := "", ""
			if cell.A.Styles()&canvas.Bold != 0 {
				fontWeight = " font-weight=\"bold\""
			}
			if cell.A.Styles()&canvas.Italics != 0 {
				fontStyle = " font-style=\"italic\""
			}
			fmt.Fprintf(&b, "<text style=\"fill:#%.03x\"%s%s x=\"%d\" y=\"%d\">",
				cell.A.RGB12FG(), fontWeight, fontStyle, x*6, y*10+8)
			switch {
			case cell.Ch < 0x20:
				b.WriteByte('?')
			case cell.Ch > 0x7f:
				b.WriteRune(cell.Ch)
			case cell.Ch == '>':
				b.WriteString("&gt;")
			case cell.Ch == '<':
				b.WriteString("&lt;")
			case cell.Ch == '&':
				b.WriteString("&amp;")
			default:
				b.WriteByte(byte(cell.Ch))
			}
			b.WriteString("</text>\n")
		}
	}

	b.WriteString(" </g>\n")
	b.WriteString("</svg>\n")
	return b.Bytes()
}

func exportPS(v view) []byte {
	const header = "%!\n" +
		"%% libcaca PDF export\n" +
		"%%LanguageLevel: 2\n" +
		"%%Pages: 1\n" +
		"%%DocumentData: Clean7Bit\n" +
		"/csquare {\n" +
		"  newpath\n" +
		"  0 0 moveto\n" +
		"  0 1 rlineto\n" +
		"  1 0 rlineto\n" +
		"  0 -1 rlineto\n" +
		"  closepath\n" +
		"  setrgbcolor\n" +
		"  fill\n" +
		"} def\n" +
		"/S {\n" +
		"  Show\n" +
		"} bind def\n" +
		"/Courier-Bold findfont\n" +
		"8 scalefont\n" +
		"setfont\n" +
		"gsave\n" +
		"6 10 scale\n"

	var b bytes.Buffer
	b.WriteString(header)
	fmt.Fprintf(&b, "0 %d translate\n", v.h)

	for y := v.h - 1; y >= 0; y-- {
		for x := 0; x < v.w; x++ {
			a := v.cells[y*v.w+x].A.ARGB64()
			fmt.Fprintf(&b, "1 0 translate\n %f %f %f csquare\n",
				float64(a[1])/0xf, float64(a[2])/0xf, float64(a[3])/0xf)
		}
		fmt.Fprintf(&b, "-%d 1 translate\n", v.w)
	}

	b.WriteString("grestore\n")
	fmt.Fprintf(&b, "0 %d translate\n", v.h*10)

	for y := v.h - 1; y >= 0; y-- {
		for x := 0; x < v.w; x++ {
			cell := v.cells[(v.h-y-1)*v.w+x]
			a := cell.A.ARGB64()
			b.WriteString("newpath\n")
			fmt.Fprintf(&b, "%d %d moveto\n", (x+1)*6, y*10+2)
			fmt.Fprintf(&b, "%f %f %f setrgbcolor\n",
				float64(a[5])/0xf, float64(a[6])/0xf, float64(a[7])/0xf)
			ch := cell.Ch
			switch {
			case ch < 0x20, ch >= 0x80:
				b.WriteString("(?) show\n")
			case ch == '\\' || ch == '(' || ch == ')':
				fmt.Fprintf(&b, "(\\%c) show\n", byte(ch))
			default:
				fmt.Fprintf(&b, "(%c) show\n", byte(ch))
			}
		}
	}
	b.WriteString("showpage\n")
	return b.Bytes()
}

func exportTroff(v view) []byte {
	names := [16]string{
		"black", "blue", "green", "cyan", "red", "magenta", "yellow", "white",
		"black", "blue", "green", "cyan", "red", "magenta", "yellow", "white",
	}
	var b bytes.Buffer
	b.WriteString(".nf\n")

	prevfg, prevbg := canvas.Color(0), canvas.Color(0)
	started := false
	for y := 0; y < v.h; y++ {
		for x := 0; x < v.w; x++ {
			cell := v.cells[y*v.w+x]
			fg, bg := cell.A.FG(), cell.A.BG()
			if fg >= 0x10 {
				fg = canvas.White
			}
			if bg >= 0x10 {
				bg = canvas.Black
			}
			if fg != prevfg || !started {
				fmt.Fprintf(&b, "\\m[%s]", names[fg])
			}
			if bg != prevbg || !started {
				fmt.Fprintf(&b, "\\M[%s]", names[bg])
			}
			if cell.A.Styles()&canvas.Bold != 0 {
				b.WriteString("\\fB")
			}
			if cell.A.Styles()&canvas.Italics != 0 {
				b.WriteString("\\fI")
			}

			switch {
			case cell.Ch == '\\':
				b.WriteString("\\\\")
			case cell.Ch == ' ':
				if x == 0 || x == v.w-1 {
					b.WriteString("\xc2\xa0")
				} else {
					b.WriteByte(' ')
				}
			default:
				b.WriteRune(cell.Ch)
			}

			if cell.A.Styles()&(canvas.Bold|canvas.Italics) != 0 {
				b.WriteString("\\fR")
			}
			prevfg, prevbg = fg, bg
			started = true
		}
		b.WriteByte('\n')
	}
	return b.Bytes()
}

func exportBBFR(v view) []byte {
	var b bytes.Buffer
	b.WriteString("[font=Courier New]")
	for y := 0; y < v.h; y++ {
		for x := 0; x < v.w; {
			cell := v.cells[y*v.w+x]
			n := 1
			if cell.Ch == ' ' {
				for x+n < v.w && v.cells[y*v.w+x+n].A == cell.A && v.cells[y*v.w+x+n].Ch == ' ' {
					n++
				}
			} else {
				// libcaca groups a non-space run by attribute alone; spaces
				// inside the run become underscores.
				for x+n < v.w && v.cells[y*v.w+x+n].A == cell.A {
					n++
				}
			}

			needBack := cell.A.BG() < 0x10
			needFront := cell.A.FG() < 0x10
			if needBack {
				fmt.Fprintf(&b, "[f=#%06x]", cell.A.RGB24BG())
			}
			if cell.Ch == ' ' {
				fmt.Fprintf(&b, "[c=#%06x]", cell.A.RGB24BG())
			} else if needFront {
				fmt.Fprintf(&b, "[c=#%06x]", cell.A.RGB24FG())
			}

			if cell.A.Styles()&canvas.Bold != 0 {
				b.WriteString("[g]")
			}
			if cell.A.Styles()&canvas.Italics != 0 {
				b.WriteString("[i]")
			}
			if cell.A.Styles()&canvas.Underline != 0 {
				b.WriteString("[s]")
			}

			for i := 0; i < n; i++ {
				ch := v.cells[y*v.w+x+i].Ch
				switch {
				case ch == canvas.MagicFullwidth:
					// skip
				case ch == ' ':
					b.WriteByte('_')
				default:
					b.WriteRune(ch)
				}
			}

			if cell.A.Styles()&canvas.Underline != 0 {
				b.WriteString("[/s]")
			}
			if cell.A.Styles()&canvas.Italics != 0 {
				b.WriteString("[/i]")
			}
			if cell.A.Styles()&canvas.Bold != 0 {
				b.WriteString("[/g]")
			}
			if cell.Ch == ' ' || needFront {
				b.WriteString("[/c]")
			}
			if needBack {
				b.WriteString("[/f]")
			}
			x += n
		}
		b.WriteByte('\n')
	}
	b.WriteString("[/font]\n")
	return b.Bytes()
}
