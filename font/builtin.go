package font

import (
	_ "embed"
	"errors"
	"strings"
	"sync"
)

// ErrBuiltinFont is returned for an unknown built-in font name.
var ErrBuiltinFont = errors.New("font: no such built-in font")

// The blobs are the exact byte arrays compiled into caca/font.c through
// mono9.data and monobold12.data. They are generated by tools/makefont.c and
// covered by the upstream WTFPL licence.
//
//go:embed data/mono9.bin
var mono9Data []byte

//go:embed data/monobold12.bin
var monobold12Data []byte

var (
	mono9Once    sync.Once
	mono9Font    *BitmapFont
	mono9Err     error
	monoboldOnce sync.Once
	monoboldFont *BitmapFont
	monoboldErr  error
)

// BuiltinNames returns the names accepted by LoadBuiltin, matching the
// strings caca_load_font() understands.
func BuiltinNames() []string {
	return []string{"Monospace 9", "Monospace Bold 12"}
}

// LoadBuiltin loads one of the bitmap fonts bundled with libcaca. The result
// is cached, so repeated calls are cheap; the returned font is read-only.
func LoadBuiltin(name string) (*BitmapFont, error) {
	switch strings.ToLower(name) {
	case "monospace 9", "mono9":
		mono9Once.Do(func() { mono9Font, mono9Err = LoadBitmapFont(mono9Data) })
		return mono9Font, mono9Err
	case "monospace bold 12", "monobold12":
		monoboldOnce.Do(func() { monoboldFont, monoboldErr = LoadBitmapFont(monobold12Data) })
		return monoboldFont, monoboldErr
	}
	return nil, ErrBuiltinFont
}
